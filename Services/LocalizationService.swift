import Foundation
import SwiftUI

// MARK: - 国际化服务
class LocalizationService: ObservableObject {
    nonisolated(unsafe) static let shared = LocalizationService()

    @Published var currentLanguage: Language {
        didSet {
            WaifuXPreferences.shared.set(currentLanguage.rawValue, forKey: "app_language")
            NotificationCenter.default.post(name: .appLanguageDidChange, object: nil)
        }
    }

    enum Language: String, CaseIterable {
        case english = "en"
        case chinese = "zh-Hans"
        case japanese = "ja"
        case spanish = "es"

        var displayName: String {
            switch self {
            case .english: return "English"
            case .chinese: return "中文"
            case .japanese: return "日本語"
            case .spanish: return "Español (España)"
            }
        }
    }

    private init() {
        // ⚠️ 不在 init 中读 UserDefaults，避免 _CFXPreferences 递归栈溢出
        // 使用系统检测的默认语言作为占位符
        self.currentLanguage = Self.detectSystemLanguage()
    }

    /// 延迟恢复用户保存的语言偏好（必须在 applicationDidFinishLaunching 中调用）
    func restoreSavedSettings() {
        if let saved = WaifuXPreferences.shared.string(forKey: "app_language"),
           let language = Language(rawValue: saved) {
            self.currentLanguage = language
        } else {
            // 重新检测系统语言（init 时用的就是默认值）
            self.currentLanguage = Self.detectSystemLanguage()
        }
    }

    private static func detectSystemLanguage() -> Language {
        let preferredLanguages = Locale.preferredLanguages

        for languageCode in preferredLanguages {
            let lowercased = languageCode.lowercased()

            // 检测中文
            if lowercased.hasPrefix("zh") {
                return .chinese
            }
            // 检测日文
            if lowercased.hasPrefix("ja") {
                return .japanese
            }
            if lowercased.hasPrefix("es") {
                return .spanish
            }
            // 检测英文
            if lowercased.hasPrefix("en") {
                return .english
            }
        }

        // 默认返回英语
        return .english
    }

    func setLanguage(_ language: Language) {
        withAnimation(.easeInOut(duration: 0.2)) {
            currentLanguage = language
        }
    }

    // 本地化字符串
    func t(_ key: String) -> String {
        translations[currentLanguage]?[key] ?? translations[.english]?[key] ?? key
    }
}

